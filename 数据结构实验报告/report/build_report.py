def clone_para(model, text):
    """复制模板段落的格式，替换其中的文字（去掉红色占位色）。"""
    new = copy.deepcopy(model._p)
    runs = new.findall(qn('w:r'))
    r_model = copy.deepcopy(runs[0]) if runs else None
    for ch in list(new):
        if ch.tag != qn('w:pPr'):
            new.remove(ch)
    if text:
        r = r_model if r_model is not None else new.makeelement(qn('w:r'), {})
        for ch in list(r):
            if ch.tag != qn('w:rPr'):
                r.remove(ch)
        rPr = r.find(qn('w:rPr'))
        if rPr is not None:
            for c in rPr.findall(qn('w:color')):
                rPr.remove(c)
        t = r.makeelement(qn('w:t'), {})
        t.text = text
        t.set(XS, 'preserve')
        r.append(t)
        new.append(r)
    return new


