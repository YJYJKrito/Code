def insert(anchor, elements):
    for el in elements:
        anchor._p.addprevious(el)


def set_cell(tc, text):
    ps = tc.findall(qn('w:p'))
    for extra in ps[1:]:
        tc.remove(extra)
    p = ps[0]
    runs = p.findall(qn('w:r'))
    for extra in runs[1:]:
        p.remove(extra)
    if runs:
        r = runs[0]
    else:
        r = p.makeelement(qn('w:r'), {})
        p.append(r)
    for ch in list(r):
        if ch.tag != qn('w:rPr'):
            r.remove(ch)
    t = r.makeelement(qn('w:t'), {})
    t.text = text
    t.set(XS, 'preserve')
    r.append(t)


def make_table(rows):
    tbl = copy.deepcopy(TBL_MODEL)
    trs = tbl.findall(qn('w:tr'))
    data_model = trs[1]
    for tr in trs[1:]:
        tbl.remove(tr)
    for tc, val in zip(trs[0].findall(qn('w:tc')), rows[0]):
        set_cell(tc, val)
    for row in rows[1:]:
        tr = copy.deepcopy(data_model)
        tbl.append(tr)
        for tc, val in zip(tr.findall(qn('w:tc')), row):
            set_cell(tc, val)
    return tbl


